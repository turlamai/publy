// Generate public web assets from the committed prototype, including packaged-server copies.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const css=read('design/prototype/public-web.css');
const js=read('design/prototype/public-web.js');
const template=read('design/prototype/setup.html').replace('<link rel="stylesheet" href="public-web.css">','<style>__WEB_CSS__</style>').replace('<script src="public-web.js"></script>','<script>__WEB_JS__</script>').replace(/<script>\n\/\/ Prototype only:[\s\S]*?<\/script>/,'<script>__SETUP_JS__</script>');
const outputs={ 'docs/web.css':css, 'docs/site.js':js,
  'packages/server/src/web-assets.ts':'// Generated by scripts/sync-public-web.mjs; edit design/prototype sources.\n'+
  'export const WEB_CSS = '+JSON.stringify(css)+';\nexport const WEB_JS = '+JSON.stringify(js)+';\nexport const SETUP_TEMPLATE = '+JSON.stringify(template)+';\n' };
let bad=false;
for(const [name,value] of Object.entries(outputs)){
  if(process.argv.includes('--check')){if(!fs.existsSync(path.join(root,name))||read(name)!==value){console.error('Stale public web asset: '+name);bad=true}}
  else fs.writeFileSync(path.join(root,name),value);
}
if(bad)process.exitCode=1;
